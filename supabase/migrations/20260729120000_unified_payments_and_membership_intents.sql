create table if not exists public.membership_payment_intents (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  plan text not null
    check (plan in ('one_month', 'three_months', 'six_months')),
  expected_amount integer not null check (expected_amount > 0),
  credit_amount integer not null default 0 check (credit_amount >= 0),
  status text not null default 'active'
    check (status in ('active', 'superseded', 'expired', 'completed', 'cancelled')),
  opened_at timestamptz not null default now(),
  ended_at timestamptz,
  expires_at timestamptz not null,
  completed_at timestamptz,
  groble_payment_event_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (ended_at is null or ended_at >= opened_at),
  check (expires_at > opened_at)
);

create unique index if not exists membership_payment_intents_one_active_per_user_idx
on public.membership_payment_intents(user_id)
where status = 'active' and ended_at is null;

create index if not exists membership_payment_intents_user_interval_idx
on public.membership_payment_intents(user_id, opened_at desc, expires_at);

create table if not exists public.payment_transactions (
  id bigint generated by default as identity primary key,
  provider text not null,
  provider_event_id text not null,
  merchant_uid text,
  user_id uuid references public.profiles(user_id) on delete set null,
  payment_kind text not null
    check (
      payment_kind in (
        'one_time',
        'membership_initial',
        'membership_upgrade',
        'membership_renewal',
        'unknown'
      )
    ),
  product_code text not null,
  amount integer not null check (amount >= 0),
  currency text not null default 'KRW',
  status text not null default 'completed'
    check (
      status in (
        'completed',
        'cancel_requested',
        'cancelled',
        'refunded'
      )
    ),
  occurred_at timestamptz not null,
  cancel_requested_at timestamptz,
  cancelled_at timestamptz,
  application_group_id uuid,
  membership_payment_intent_id bigint
    references public.membership_payment_intents(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (provider, provider_event_id)
);

create index if not exists payment_transactions_user_occurred_idx
on public.payment_transactions(user_id, occurred_at desc);

create index if not exists payment_transactions_kind_occurred_idx
on public.payment_transactions(payment_kind, occurred_at desc);

create index if not exists payment_transactions_merchant_uid_idx
on public.payment_transactions(provider, merchant_uid)
where merchant_uid is not null;

alter table public.groble_webhook_events
  add column if not exists matched_membership_payment_intent_id bigint
    references public.membership_payment_intents(id) on delete set null,
  add column if not exists payment_kind text,
  add column if not exists payment_amount integer;

create index if not exists groble_webhook_events_membership_intent_idx
on public.groble_webhook_events(matched_membership_payment_intent_id)
where matched_membership_payment_intent_id is not null;

