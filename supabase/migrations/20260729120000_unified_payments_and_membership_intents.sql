create or replace function public.activate_membership_payment_intent(
  p_user_id uuid,
  p_plan text,
  p_expected_amount integer,
  p_credit_amount integer default 0
)
returns table (
  intent_id bigint,
  opened_at timestamptz,
  expires_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
declare
  intent_record public.membership_payment_intents%rowtype;
  switched_at timestamptz := clock_timestamp();
begin
  if p_plan not in ('one_month', 'three_months', 'six_months') then
    raise exception 'Unsupported membership plan.';
  end if;
  if p_expected_amount <= 0 or p_credit_amount < 0 then
    raise exception 'Invalid membership payment amount.';
  end if;

  update public.membership_payment_intents as intent
  set
    status = case
      when intent.expires_at <= switched_at then 'expired'
      else 'superseded'
    end,
    ended_at = least(switched_at, intent.expires_at),
    updated_at = switched_at
  where intent.user_id = p_user_id
    and intent.status = 'active'
    and intent.ended_at is null;

  insert into public.membership_payment_intents (
    user_id,
    plan,
    expected_amount,
    credit_amount,
    status,
    opened_at,
    expires_at,
    created_at,
    updated_at
  )
  values (
    p_user_id,
    p_plan,
    p_expected_amount,
    p_credit_amount,
    'active',
    switched_at,
    switched_at + interval '2 hours',
    switched_at,
    switched_at
  )
  returning * into intent_record;

  return query
  select intent_record.id, intent_record.opened_at, intent_record.expires_at;
end;
$$;

revoke all on function public.activate_membership_payment_intent(
  uuid,
  text,
  integer,
  integer
) from public, anon, authenticated;
grant execute on function public.activate_membership_payment_intent(
  uuid,
  text,
  integer,
  integer
) to service_role;

create or replace function public.match_membership_payment_intent(
  p_user_id uuid,
  p_paid_at timestamptz,
  p_amount integer
)
returns table (
  intent_id bigint,
  plan text,
  credit_amount integer
)
language sql
stable
security definer
set search_path = public
as $$
  select
    intent.id as intent_id,
    intent.plan,
    intent.credit_amount
  from public.membership_payment_intents as intent
  where intent.user_id = p_user_id
      and (
        intent.expected_amount = p_amount
        or (
          intent.credit_amount > 0
          and intent.expected_amount - intent.credit_amount = p_amount
        )
      )
    and intent.opened_at <= p_paid_at
    and p_paid_at < intent.expires_at
    and (intent.ended_at is null or p_paid_at < intent.ended_at)
    and intent.status in ('active', 'superseded')
  order by intent.opened_at desc
  limit 2;
$$;

revoke all on function public.match_membership_payment_intent(
  uuid,
  timestamptz,
  integer
) from public, anon, authenticated;
grant execute on function public.match_membership_payment_intent(
  uuid,
  timestamptz,
  integer
) to service_role;

insert into public.payment_transactions (
  provider,
  provider_event_id,
  merchant_uid,
  user_id,
  payment_kind,
  product_code,
  amount,
  status,
  occurred_at,
  application_group_id
)
select
  'groble',
  webhook.event_id,
  webhook.merchant_uid,
  webhook.matched_user_id,
  'one_time',
  'meeting_date_ticket',
  application.deposit_amount,
  'completed',
  coalesce(webhook.occurred_at, webhook.received_at),
  webhook.matched_application_group_id
from public.groble_webhook_events as webhook
join public.meeting_date_applications as application
  on application.application_group_id = webhook.matched_application_group_id
 and application.user_id = webhook.matched_user_id
where webhook.event_type = 'payment.completed'
  and webhook.processing_status = 'processed'
  and webhook.matched_user_id is not null
  and webhook.matched_application_group_id is not null
on conflict (provider, provider_event_id) do nothing;
