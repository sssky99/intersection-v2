-- Public products and internal operations are intentionally separate:
-- ticket_templates are reusable programs, meeting_events are public sale units,
-- and meeting_groups are private table/location assignments.

create table if not exists public.meeting_events (
  id uuid primary key default gen_random_uuid(),
  program_id uuid not null references public.ticket_templates(id) on delete restrict,
  title text not null,
  short_description text,
  event_date date not null,
  starts_at time not null,
  region text not null default '서울',
  visibility text not null default 'draft'
    check (visibility in ('draft', 'test_only', 'public', 'closed', 'archived')),
  application_opens_at timestamptz,
  application_closes_at timestamptz,
  capacity integer not null default 30 check (capacity > 0),
  confirmed_application_count integer not null default 0
    check (confirmed_application_count >= 0),
  price_amount integer not null default 0 check (price_amount >= 0),
  currency text not null default 'KRW',
  detail_snapshot jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists meeting_events_program_date_time_uidx
on public.meeting_events(program_id, event_date, starts_at);

create index if not exists meeting_events_public_schedule_idx
on public.meeting_events(visibility, event_date, starts_at)
where visibility in ('public', 'test_only');

create table if not exists public.meeting_event_stages (
  id uuid primary key default gen_random_uuid(),
  event_id uuid not null references public.meeting_events(id) on delete cascade,
  title text not null,
  stage_type text not null default 'activity'
    check (stage_type in ('meal', 'activity', 'feedback', 'other')),
  sequence integer not null check (sequence > 0),
  starts_at time,
  location_mode text not null default 'shared'
    check (location_mode in ('shared', 'group_specific', 'hidden')),
  place_name text,
  address text,
  place_payload jsonb,
  reveal_offset_minutes integer not null default 1440
    check (reveal_offset_minutes >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(event_id, sequence)
);

create index if not exists meeting_event_stages_event_idx
on public.meeting_event_stages(event_id, sequence);

create table if not exists public.meeting_groups (
  id uuid primary key default gen_random_uuid(),
  event_id uuid not null references public.meeting_events(id) on delete cascade,
  code text not null,
  title text not null,
  capacity integer not null default 6 check (capacity > 0),
  status text not null default 'draft'
    check (status in ('draft', 'ready', 'confirmed', 'cancelled')),
  operation_note text,
  legacy_ticket_instance_id uuid unique
    references public.ticket_instances(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(event_id, code)
);

create index if not exists meeting_groups_event_idx
on public.meeting_groups(event_id, status, code);

create table if not exists public.meeting_group_stage_locations (
  id uuid primary key default gen_random_uuid(),
  group_id uuid not null references public.meeting_groups(id) on delete cascade,
  stage_id uuid not null references public.meeting_event_stages(id) on delete cascade,
  place_name text,
  address text,
  place_payload jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(group_id, stage_id)
);

create table if not exists public.meeting_event_rejections (
  id bigint generated by default as identity primary key,
  event_id uuid not null references public.meeting_events(id) on delete cascade,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  created_at timestamptz not null default now(),
  unique(event_id, user_id)
);

